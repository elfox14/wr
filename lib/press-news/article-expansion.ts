type NewsLike = {
  id: string;
  title: string;
  body?: string | null;
  category?: string | null;
  tags?: unknown;
};

type PressNewsMeta = {
  keywords?: string[];
  flagA?: string;
  flagB?: string;
  score?: string;
  label?: string;
};

function parseMeta(tags: unknown): PressNewsMeta {
  if (!tags) return {};
  if (typeof tags === 'string') {
    try {
      return parseMeta(JSON.parse(tags));
    } catch {
      return { keywords: tags.split(',').map((item) => item.trim()).filter(Boolean) };
    }
  }
  if (Array.isArray(tags)) return { keywords: tags.map((item) => String(item).trim()).filter(Boolean) };
  if (typeof tags === 'object') return tags as PressNewsMeta;
  return {};
}

function extractTeams(title: string) {
  const cleaned = title.replace(/\s+/g, ' ').trim();
  const patterns = [
    /(.+?)\s+(?:تفتتح|تقلب|تحصد|تضرب|تخطف|يتعادلان|تعود|تفاجئ|تمطر|يصدم|تفرض|تقترب|ترد|يبدأ|يعادل|تكسر|تتعادل|تسحق)\s+(.+?)(?:\s+\d|\s+في|\s+أمام|\s+على|$)/,
    /(.+?)\s+×\s+(.+)/,
    /(.+?)\s+ضد\s+(.+)/,
  ];
  for (const pattern of patterns) {
    const match = cleaned.match(pattern);
    if (match?.[1] && match?.[2]) return [match[1].trim(), match[2].trim()];
  }
  return ['الفريق الأول', 'الفريق الثاني'];
}

function compactTitle(title: string) {
  return title.replace(/\s+/g, ' ').trim();
}

